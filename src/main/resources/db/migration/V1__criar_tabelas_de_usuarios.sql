CREATE TABLE TB_CV_USUARIO (
    ID_USUARIO   BIGINT IDENTITY(1,1) PRIMARY KEY,
    NOME         VARCHAR(100) NOT NULL,
    EMAIL        VARCHAR(120) NOT NULL,
    SENHA        VARCHAR(100),
    PERFIL       VARCHAR(20),
    PROVEDOR     VARCHAR(20)  NOT NULL,
    DATA_CRIACAO DATETIME2    NOT NULL,
    CONSTRAINT UK_CV_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_CV_USUARIO_PERFIL CHECK (PERFIL IN ('TUTOR', 'VETERINARIO')),
    CONSTRAINT CK_CV_USUARIO_PROVEDOR CHECK (PROVEDOR IN ('LOCAL', 'GOOGLE', 'GITHUB'))
);

CREATE TABLE TB_CV_TUTOR (
    ID_TUTOR   BIGINT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO BIGINT       NOT NULL,
    CPF        VARCHAR(14)  NOT NULL,
    TELEFONE   VARCHAR(20)  NOT NULL,
    CONSTRAINT UK_CV_TUTOR_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UK_CV_TUTOR_CPF UNIQUE (CPF),
    CONSTRAINT FK_CV_TUTOR_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_CV_USUARIO (ID_USUARIO)
);

CREATE TABLE TB_CV_VETERINARIO (
    ID_VETERINARIO BIGINT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO     BIGINT        NOT NULL,
    CRMV           VARCHAR(20)   NOT NULL,
    ESPECIALIDADE  VARCHAR(100)  NOT NULL,
    TELEFONE       VARCHAR(20)   NOT NULL,
    CONSTRAINT UK_CV_VETERINARIO_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UK_CV_VETERINARIO_CRMV UNIQUE (CRMV),
    CONSTRAINT FK_CV_VETERINARIO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_CV_USUARIO (ID_USUARIO)
);